    ("REPL_GUIDE.md", FREE / "REPL_GUIDE.md"),
    ("REPL_GUIDE.md", MCP / "REPL_GUIDE.md"),
    # ⚠ paracore-forge gets the engine doc so a Forge-written tool knows the real API instead of
