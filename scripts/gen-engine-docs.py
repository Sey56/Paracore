# A repo may own EXTRA extension methods — its "pack". Those are declared IN the repo and are
# APPENDED to the generic engine doc, so the reference a client serves is
# "generic engine methods + this repo's pack methods".
# ⚠ EMPTY today, and that is CORRECT: `paracore-takeoff` is the only repo with a `pack/`, and
# takeoff is a DETERMINISTIC tool server — it does not serve EXTENSION_METHODS.md at all.
# ⚠⚠ Its pack methods are still INDEXED, just in its OWN document, generated by the same tool:
#       gen-ext-methods.py --pack <paracore-takeoff> --doc Docs/PACK_METHOD_INDEX.md --write
# Add an entry here only when a pack-bearing repo starts serving the ENGINE doc itself, e.g.
# { MODEL / "EXTENSION_METHODS.md": MODEL / "Docs" / "PACK_METHODS.md" }.
PACK_APPENDIX: dict[Path, Path] = {}


def render_shared_skills() -> str:
    """The nine shared skill sections, for the `SKILLS.md` catalogue region.

    ⚠ The two views of the set must cover the SAME nine names. A skill added to one and not the
    other would ship a catalogue entry with no routing line, or a routing line for nothing.
    FAILS rather than emitting a partial region — a short region must never look like success.
    """
    mismatch = set(SHARED_SKILLS) ^ set(SHARED_SKILL_WHEN)
    if mismatch:
        raise ValueError(
            "SHARED_SKILL_DESCRIPTIONS and SHARED_SKILL_WHEN disagree on: "
            f"{sorted(mismatch)}"
        )
    lines = [
        "⚠ **GENERATED — do not edit this region.** These nine are the **shared REPL / "
        "dynamic-execution set**: they teach the GENERIC engine's own methods, so they are "
        "identical in every engine-driving MCP. Authority: "
        "`paracore/mcp/mcp_core/shared_skills.py` — the shared MCP core, which every MCP "
        "IMPORTS instead of copying. The full text of each lives in "
        "`paracore/mcp/mcp_core/skills/<name>/SKILL.md`.",
        "",
    ]
    for name in SHARED_SKILLS:
        lines += [
            f"## {name}",
            "",
            SHARED_SKILL_DESCS[name],
            "",
            f"**When:** {SHARED_SKILL_WHEN[name]}",
            f"**Detail:** `{name}/SKILL.md`",
            "",
        ]
    return "\n".join(lines).rstrip() + "\n"


def build(relname: str, dest: Path | None = None) -> str:
    """The intended content of one destination: the authority, plus its pack appendix if any.

    ⚠ For `EXTENSION_METHODS.md` the API INDEX REGION is re-generated from the engine source
    here, so the bytes handed to every destination are produced by the same expression. That
    is deliberate: it makes the index identical everywhere by construction. It also means this
    function alone cannot prove the index is CORRECT — see `.repl/verify_ext_method_gen.py`,
    which checks it against the compiled XML sidecar and the DLL (independent artefacts).

    ⚠ For a `SELF` destination (`SKILLS.md`) the FILE IS ITS OWN AUTHORITY: its prose is local and
    hand-authored, and only the marked region is generated. Reading it here rather than copying an
    authority is what lets each repo keep a different set of DOMAIN skills.
    """
    if relname == SELF:
        if dest is None or not dest.exists():
            raise FileNotFoundError(f"self-authority target missing: {dest}")
        return _GEM.inject(
            dest.read_text(encoding="utf-8"),
            render_shared_skills(),
            SKILLS_BEGIN,
            SKILLS_END,
        )
    src = authority_root(relname) / relname
    if not src.exists():
        raise FileNotFoundError(f"authority missing: {src}")
    text = src.read_text(encoding="utf-8")
    if relname == "EXTENSION_METHODS.md":
        body = _GEM.render_index(
            _GEM.engine_records(),
            provenance="`CoreScript.Engine/`",
            with_globals=True,
        )
        text = _GEM.inject(text, body)
    appendix = PACK_APPENDIX.get(dest) if dest is not None else None
    if appendix is not None and appendix.exists():
        text = text.rstrip() + "\n\n" + appendix.read_text(encoding="utf-8").lstrip()
    return text


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="report drift, do not write")
    ap.add_argument("--write", action="store_true", help="regenerate outputs")
    args = ap.parse_args()
    if not (args.check or args.write):
        ap.error("pass --check or --write")

    stale, written, missing = [], [], []

    def sync(dest: Path, want: str, label: str) -> None:
        have = dest.read_text(encoding="utf-8") if dest.exists() else None
        # compare modulo line endings: git normalizes to LF in both repos
        same = have is not None and have.replace("\r\n", "\n") == want.replace("\r\n", "\n")
        if same:
            print(f"  ok      {label}")
            return
        if have is None:
            missing.append(dest)
            print(f"  MISSING {label}")
        else:
            stale.append(dest)
            print(f"  STALE   {label}")
        if args.write:
            dest.parent.mkdir(parents=True, exist_ok=True)
            dest.write_text(want, encoding="utf-8", newline="\n")
            written.append(dest)

    for relname, dest in TARGETS:
        try:
            want = build(relname, dest)
        except FileNotFoundError as e:
            print(f"  ERROR   {relname}: {e}")
            return 2
        sync(dest, want, f"{relname} -> {dest}")

    # ⚠ The takeoff skill copies. Same gate as everything else: a changed `Docs/*.md` whose
    #   skill copy was not regenerated is DRIFT, and DRIFT fails.
    for src, dest, header in COPY_TARGETS:
        if not src.exists():
            print(f"  ERROR   copy source missing: {src}")
            return 2
        sync(dest, header + src.read_text(encoding="utf-8").lstrip(), f"copy {src.name} -> {dest}")

    print()
    total = len(TARGETS) + len(COPY_TARGETS)
    if args.write:
        print(f"wrote {len(written)} file(s); {len(stale) + len(missing)} were out of date")
        return 0
    if stale or missing:
        print(f"DRIFT: {len(stale)} stale, {len(missing)} missing — run --write")
        return 1
    print(f"generated docs are up to date ({total} targets)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
